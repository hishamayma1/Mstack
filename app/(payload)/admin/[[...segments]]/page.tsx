import type { Metadata } from "next"

import config from "@payload-config"
import "@payloadcms/next/css"
import { RootPage, generatePageMetadata } from "@payloadcms/next/views"
import { importMap } from "../importMap"

// The admin is an authenticated app shell: every render reads the session
// cookie and hits the database, so there is nothing here to prerender and no
// useful Suspense boundary to add — Payload owns the whole subtree.
//
// `cacheComponents` (next.config.mjs) validates that routes can be prerendered
// and warns when they can't. `instant = false` opts this route out of that
// validation. It does not change how the route renders; it stays a blocking,
// request-time render, which is correct for an admin panel.
//
// Note: this file is generated by Payload. If it is ever regenerated, this
// export needs adding back.
export const instant = false

type Args = {
  params: Promise<{
    segments: string[]
  }>
  searchParams: Promise<{
    [key: string]: string | string[]
  }>
}

export const generateMetadata = ({ params, searchParams }: Args): Promise<Metadata> =>
  generatePageMetadata({ config, params, searchParams })

const Page = ({ params, searchParams }: Args) =>
  RootPage({ config, params, searchParams, importMap })

export default Page
